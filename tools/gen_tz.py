#!/usr/bin/env python3
"""Generate main/tz_db.h: IANA timezone names ("Asia/Dubai") -> POSIX TZ
strings ("<+04>-4"), which is what newlib's TZ variable understands.

    tools/gen_tz.py [/usr/share/zoneinfo] > main/tz_db.h

Every TZif v2+ file ends with its POSIX TZ string on a line of its own; that
footer is taken from each zone in the system's tzdata.
"""
import os
import sys

root = sys.argv[1] if len(sys.argv) > 1 else "/usr/share/zoneinfo"
SKIP_DIRS = {"posix", "right"}
SKIP = {"posixrules", "localtime", "Factory", "leapseconds", "tzdata.zi"}

zones = {}
for dirpath, dirnames, filenames in os.walk(root):
    dirnames[:] = [d for d in dirnames
                   if not (dirpath == root and d in SKIP_DIRS)]
    for f in filenames:
        path = os.path.join(dirpath, f)
        name = os.path.relpath(path, root)
        if name in SKIP or "." in f:
            continue
        with open(path, "rb") as fp:
            data = fp.read()
        if not data.startswith(b"TZif") or data[4:5] < b"2":
            continue
        footer = data.rstrip(b"\n").rsplit(b"\n", 1)[-1].decode("ascii")
        if footer:
            zones[name] = footer

if "UTC" not in zones:
    zones["UTC"] = "UTC0"

out = sys.stdout
out.write("/* Generated by tools/gen_tz.py from the tzdata in %s; do not edit.\n"
          " * IANA timezone name -> POSIX TZ string, sorted by name. */\n" % root)
out.write("#pragma once\n\n")
out.write("typedef struct { const char *name, *posix; } tz_entry_t;\n\n")
out.write("static const tz_entry_t tz_db[] = {\n")
for name in sorted(zones):
    out.write('    { "%s", "%s" },\n' % (name, zones[name]))
out.write("};\n")
